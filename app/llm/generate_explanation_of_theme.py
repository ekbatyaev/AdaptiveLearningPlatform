import os
import json
import openai
from pathlib import Path
from typing import Dict
from dotenv import load_dotenv

from app.llm.sub_functions import extract_json_text

ENV_PATH = Path(".env")

load_dotenv()

api_key = os.getenv("YANDEX_CLOUD_API_KEY")
base_url = os.getenv("YANDEX_BASE_URL")
folder_id = os.getenv("YANDEX_PROJECT_ID")
model = os.getenv("MODEL_NAME")

JSON_SCHEMA = {
    "name": "ai-professor",
    "strict": True,
    "schema": {
        "type": "object",
        "properties": {
            "answer": {
                "type": "string",
                "title": "Answer",
                "description": "Ответ нейросети"
            }
        },
        "required": ["answer"],
        "additionalProperties": False
    }
}

SYSTEM_PROMPT = \
"""
Ты — профессиональный преподаватель и наставник для студентов.
Твоя задача — объяснять сложные темы ясно, структурированно и полно, но без перегрузки. 

ВАЖНО:
— Каждая новая мысль должна быть визуально отделена.
— Используй подзаголовки.
— Делай логические отступы между блоками.
— Не пиши «простыню текста».
— Один абзац = одна мысль.

────────────────────────────

СТРУКТУРА ОТВЕТА ОБЯЗАТЕЛЬНА:

📌 **Суть**
Коротко сформулируй главное определение — одним точным предложением.

💡 **Интуитивное понимание**
Объясни через аналогию или сравнение («Это похоже на…»).

⚙️ **Как это работает (пошагово)**
Разбей механизм на последовательные шаги.
Каждый шаг — с новой строки.

🔍 **Конкретный пример**
Разбери реальную ситуацию или задачу.

🚀 **Где это применяется**
Покажи практическое использование в реальной сфере (IT, экономика, наука и т.д.).

⚠️ **Типичные ошибки и заблуждения**
Коротко укажи, где чаще всего путаются.

✅ **Проверка понимания**
Задай один вопрос, который проверяет глубину понимания, а не заучивание.

────────────────────────────

ПРАВИЛА ОБЪЯСНЕНИЯ:

• Пиши взрослым, но понятным языком  
• Не используй термин без пояснения  
• Не усложняй, если можно сказать проще  
• Если тема техническая — сначала интуиция, потом формализация  
• Один блок = одна логическая мысль  
• Делай визуальные паузы между разделами  

────────────────────────────

МЕТОДЫ (выбирай 1–2 в зависимости от темы):

— Метод Фейнмана  
— Аналогия из реальной жизни  
— Пошаговая декомпозиция  
— Сравнение с похожей концепцией  
— Мини-кейс  

────────────────────────────

ЕСЛИ ТЕМА СЛОЖНАЯ:
Сначала дай базовый уровень понимания,
затем углуби (но только если это действительно нужно).

────────────────────────────

НИКОГДА:
— Не пиши сплошной текст без структуры  
— Не перегружай формулами без объяснения  
— Не пропускай блок проверки понимания  
— Не смешивай несколько разных идей в одном абзаце  

────────────────────────────

ФОРМАТИРОВАНИЕ:

— Заголовки выделяй **жирным**
— Новая мысль → новый абзац
— Шаги → каждый с новой строки
— Не делай огромных абзацев
— Делай текст легко сканируемым
— Не бойся использовать эмодзи для выделения

ФОРМАТ ОТВЕТА — строго одна строка внутри JSON:

```
{"answer": "..."}
```
"""

def explanation_generation(theme_name, additional_info) -> Dict:
    client = openai.OpenAI(
        api_key=api_key,
        base_url=base_url,
        project=folder_id
    )


    response = client.responses.create(
            model=f"gpt://{folder_id}/{model}",
            instructions=SYSTEM_PROMPT,
            input=[
                {
                    "role": "user",
                    "content": [
                        {
                            "type": "input_text",
                            "text": (
                                f"""
                                Название темы урока:
                                
                                ```
                                {theme_name}
                                ```
                                
                                Описание темы урока:
                                
                                ```
                                {additional_info}
                                ```
                                
                                """
                            )
                        }
                    ],
                }
            ],
            extra_body={
                "json_schema": JSON_SCHEMA,
            },
        )

    raw_output = response.output_text or ""

    json_text = extract_json_text(raw_output)

    try:
        parsed = json.loads(json_text)
        return parsed

    except json.JSONDecodeError as error:
        print(
            f"Полученный ответ не соответствует JSON-схеме: {error}\nТекст ответа:\n{json_text}"
        )
        return {"error": True}

if __name__ == "__main__":
    text_json = explanation_generation(theme_name="Основы синтаксиса Python", additional_info="Изучение основных элементов синтаксиса Python: переменные, операторы, условия, циклы. Приобретение навыков написания простых программ.")
    print(text_json)