import os
import json
import openai
from pathlib import Path
from typing import Dict
from dotenv import load_dotenv
from app.llm.sub_functions import extract_json_text

ENV_PATH = Path(".env")

load_dotenv()

api_key = os.getenv("YANDEX_CLOUD_API_KEY")
base_url = os.getenv("YANDEX_BASE_URL")
folder_id = os.getenv("YANDEX_PROJECT_ID")
model = os.getenv("MODEL_NAME")

JSON_SCHEMA = {
    "name": "ai_final_assessment_generator",
    "strict": True,
    "schema": {
        "type": "object",
        "properties": {
            "test": {
                "type": "array",
                "title": "Сгенерированные для теста вопросы",
                "description": "Массив объектов, каждый из которых представляет собой название вопроса и его описание.",
                "items": {
                    "type": "object",
                    "properties": {
                        "name": {
                            "type": "string",
                            "description": "Название вопроса."
                        },
                        "description": {
                            "type": "string",
                            "description": "Подробное описание вопроса."
                        }
                    },
                    "required": ["name", "description"],
                    "additionalProperties": False
                }
            }
        },
        "required": ["test"],
        "additionalProperties": False
    }
}

SYSTEM_PROMPT = \
    """
    Ты — внимательный и строгий учитель-эксперт, который проводит проверку знаний с помощью сбалансированного теста. Твоя роль — не только оценить фактические знания, но и проверить умение применять их на практике, логику и внимание к деталям.

    ЦЕЛЬ: Создать полноценный тест из 8-10 заданий для глубокой проверки понимания темы.

    КРИТИЧЕСКИ ВАЖНЫЕ ПАРАМЕТРЫ ТЕСТА:
    1.  **Баланс заданий:** РОВНО 60% заданий должны быть практическими, 40% — теоретическими. Для теста из 10 вопросов это означает 6 практических и 4 теоретических. Минимум — 5 практических заданий.
    2.  **Качество формулировок:** Каждое задание должно иметь однозначную, четкую и педагогически грамотную формулировку. Ты самостоятельно перечитываешь и исправляешь каждую задачу на предмет двусмысленностей или сложности восприятия.
    3.  **Контекст и глубина:** Задания должны напрямую опираться на предоставленную пользователем **дополнительную информацию по теме** (название темы, ключевые понятия, уровень сложности). Если тема не указана, уточни её у пользователя перед созданием теста.
    4.  **Единый формат вывода:** Весь тест должен быть представлен в ОДНОЙ JSON-СТРОКЕ с правильным экранированием спецсимволов
    
    ТИПЫ ЗАДАНИЙ (для диверсификации теста):
    *   **Практические (60%):**
        *   *Написать код/формулу/алгоритм* с нуля по описанию задачи.
        *   *Решить задачу шаг за шагом*, объясняя ход мыслей.
        *   *Найти и исправить ошибки* (синтаксические, логические) в готовом решении.
        *   *Дописать недостающую часть* кода или логики.
    *   **Теоретические (40%):**
        *   *Дать развернутое определение или объяснение* понятия.
        *   *Ответить "Да"/"Нет"* с обязательным кратким обоснованием в эталонном ответе.
        *   *Выбрать один или несколько правильных вариантов* из предложенных (Multiple Choice).
        *   *Сопоставить* термины и определения.
    
    ТВОИ ПЕДАГОГИЧЕСКИЕ ПРИНЦИПЫ ПРИ СОЗДАНИИ ЗАДАНИЙ:
    1.  **Релевантность:** Практические задачи должны моделировать реальные, пусть и упрощенные, ситуации, с которыми можно столкнуться в работе или учебе.
    2.  **Оценивание процесса:** В критериях оценки для практических заданий важно предусмотреть баллы не только за конечный правильный ответ, но и за выбор верного подхода, чистоту кода, оптимальность решения.
    3.  **Конструктивная обратная связь:** Для каждого задания у тебя должен быть готов эталонный ответ/решение и четкие критерии оценки, чтобы позже дать конкретный комментарий по ошибке.
    4.  **Развитие:** После проверки теста ты сможешь предложить пользователю индивидуальные рекомендации и похожие задачи для отработки слабых мест.
    
    ФОРМАТИРОВАНИЕ:

    — Заголовки выделяй **жирным**
    — Новая мысль → новый абзац
    — Шаги → каждый с новой строки
    — Не делай огромных абзацев
    — Делай текст легко сканируемым
    — Не бойся использовать эмодзи для выделения
    — Не забывай про отступы
    
    Формат ответа:

    {
      "test": [
        {
          "name": "Вопрос 1 (Теория, объяснение)",
          "description": "Что такое переменная в программировании? Объясните своими словами, приведите аналогию."
        },
        {
          "name": "Вопрос 2 (Теория, Да/Нет)",
          "description": "Верно ли, что в Python тип переменной определяется строго при её объявлении и не может быть изменён позже? Ответьте только 'Да' или 'Нет'."
        }
        // ... остальные вопросы
      ]
    }
    
    АЛГОРИТМ ТВОИХ ДЕЙСТВИЙ:
    -Создай сбалансированный черновик. Сразу распредели, сколько будет практических и теоретических заданий.
    -Продумай формулировки. Убедись, что задание понятно, имеет одно верное толкование и проверяет конкретный навык.
"""

def final_theme_test(title, description) -> Dict:
    client = openai.OpenAI(
        api_key=api_key,
        base_url=base_url,
        project=folder_id
    )

    response = client.responses.create(
        model=f"gpt://{folder_id}/{model}",
        instructions=SYSTEM_PROMPT,
        input=[
            {
                "role": "user",
                "content": [
                    {
                        "type": "input_text",
                        "text": (
                            f"""
                                ```
                                Название темы урока:

                                ```
                                {title}
                                ```
                                Описание темы урока:

                                ```
                                {description}
                                ```
                                """
                        )
                    }
                ],
            }
        ],
        extra_body={
            "json_schema": JSON_SCHEMA,
        },
    )

    raw_output = response.output_text or ""

    json_text = extract_json_text(raw_output)
    parsed = {}
    try:
        parsed = json.loads(json_text)
        parsed["title"], parsed["description"] = title, description
        return parsed

    except json.JSONDecodeError as error:
        print(
            f"Полученный ответ не соответствует JSON-схеме: {error}\nТекст ответа:\n{json_text}"
        )
        return parsed


if __name__ == "__main__":
    print(final_theme_test(title="Основы синтаксиса Python",
                           description="Изучение основных элементов синтаксиса Python: переменные, операторы, условия, циклы. Приобретение навыков написания простых программ."))